import { afterAll, beforeAll, expect, it } from "vitest";
import { POST as start } from "@/app/api/auth/register/start/route";
import { POST as verify } from "@/app/api/auth/register/verify/route";
import { POST as complete } from "@/app/api/auth/register/complete/route";
import { GET as status } from "@/app/api/auth/register/status/route";
import { GET as captcha } from "@/app/api/auth/wa/captcha/route";
import { GET as me } from "@/app/api/auth/me/route";
import { POST as login } from "@/app/api/auth/login/route";
import { GET as customers, POST as createCustomer } from "@/app/api/customers/route";
import { POST as logoutAll } from "@/app/api/auth/logout-all/route";
import { resetRateLimits } from "@/server/http";
import { getContext } from "@/server/context";
import { startTestDaemon } from "../helpers/waDaemon";

const saved = { ...process.env };
const globalContext = globalThis as unknown as { __dukaan?: unknown };
let daemon: Awaited<ReturnType<typeof startTestDaemon>>;
const post = (path: string, body: unknown, cookie?: string) => new Request(`http://localhost${path}`, { method: "POST", headers: { "content-type": "application/json", ...(cookie ? { cookie } : {}) }, body: JSON.stringify(body) });
const get = (path: string, cookie?: string) => new Request(`http://localhost${path}`, { headers: cookie ? { cookie } : {} });
const cookieOf = (response: Response) => response.headers.get("set-cookie")!.split(";")[0];
beforeAll(async () => {
  daemon = await startTestDaemon();
  globalContext.__dukaan = undefined; resetRateLimits();
  Object.assign(process.env, { DUKAAN_MODE: "shop", DUKAAN_TEST_MEMORY: "1", DUKAAN_DB_FILE: ":memory:", PROPOSAL_SECRET: "registration-test-secret-with-enough-length", SETUP_CODE: "test-operator-code", WA_SERVICE_URL: daemon.cfg.baseUrl, WA_APP_KEY: daemon.cfg.appKey, WA_APP_SECRET: daemon.cfg.appSecret });
});
afterAll(() => { daemon.close(); process.env = { ...saved }; globalContext.__dukaan = undefined; });
async function verified(mobile: string, purpose = "signup") {
  const cap = await (await captcha(get("/api/auth/wa/captcha"))).json();
  const sent = await start(post("/api/auth/register/start", { mobile, purpose, captchaId: cap.captchaId, captchaCode: daemon.solve(cap.captchaId) }));
  expect(sent.status).toBe(200);
  expect(sent.headers.get("set-cookie")).toContain("HttpOnly");
  const browser = cookieOf(sent);
  expect((await verify(post("/api/auth/register/verify", { code: daemon.lastCode() }))).status).toBe(401);
  expect((await verify(post("/api/auth/register/verify", { code: daemon.lastCode() }, browser))).status).toBe(200);
  expect(await (await status(get("/api/auth/register/status", browser))).json()).toMatchObject({ state: "verified", purpose });
  return browser;
}
it("isolates public shops, binds proofs to browsers, safely replays and recovers an account", async () => {
  const phoneA = ["70000", "00101"].join(""); const phoneB = ["70000", "00102"].join("");
  const proofA = await verified(phoneA);
  const bodyA = { name: "Fictional owner A", shopName: "Fictional shop A", confirmed: true };
  const first = await complete(post("/api/auth/register/complete", bodyA, proofA));
  expect(first.status).toBe(200); expect(await first.clone().json()).toMatchObject({ created: true });
  const sessionA = cookieOf(first);
  const replay = await complete(post("/api/auth/register/complete", bodyA, proofA));
  expect(await replay.json()).toMatchObject({ created: false });
  const proofB = await verified(phoneB);
  const second = await complete(post("/api/auth/register/complete", { name: "Fictional owner B", shopName: "Fictional shop B", passcode: "shop-b-safe-passcode", confirmed: true }, proofB));
  expect(second.status).toBe(200); const sessionB = cookieOf(second);
  expect((await createCustomer(post("/api/customers", { name: "Only shop A" }, sessionA))).status).toBe(200);
  const [a, b] = await Promise.all([customers(get("/api/customers", sessionA)).then((r) => r.json()), customers(get("/api/customers", sessionB)).then((r) => r.json())]);
  expect(a.customers).toHaveLength(1); expect(b.customers).toHaveLength(0);
  expect(await (await me(get("/api/auth/me", sessionA))).json()).toMatchObject({ loggedIn: true, shopName: "Fictional shop A" });
  expect(await (await me(get("/api/auth/me", sessionB))).json()).toMatchObject({ loggedIn: true, shopName: "Fictional shop B" });
  expect((await login(post("/api/auth/login", { mobile: phoneB, passcode: "shop-b-safe-passcode" }))).status).toBe(200);
  await new Promise((resolve) => setTimeout(resolve, 1100));
  const recovery = await verified(phoneA, "recovery");
  const recovered = await complete(post("/api/auth/register/complete", { passcode: "shop-a-recovered-passcode", confirmed: true }, recovery));
  expect(recovered.status).toBe(200);
  expect((await customers(get("/api/customers", sessionA))).status).toBe(401);
  expect((await complete(post("/api/auth/register/complete", bodyA, proofA))).status).toBe(401);
  expect((await customers(get("/api/customers", sessionB))).status).toBe(200);
  const recoveredSession = cookieOf(recovered);
  expect((await customers(get("/api/customers", recoveredSession))).status).toBe(200);
  await logoutAll(post("/api/auth/logout-all", { confirmed: true }, sessionB));
  expect((await customers(get("/api/customers", recoveredSession))).status).toBe(200);
  expect((await customers(get("/api/customers", sessionB))).status).toBe(401);
  expect((await getContext().store.getOwnerByMobile(phoneA))?.authVersion).toBe(1);
});
