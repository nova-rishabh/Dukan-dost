import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
test.use({ viewport: { width: 390, height: 844 } });
test("exact paise are reviewed in words before writing and appear in filtered history", async ({ page, context }) => {
  const request = page.request;
  await request.post("/api/demo/start", { data: {} });
  await request.post("/api/demo/reset");
  await context.addCookies([{ name: "dukaan-locale", value: "en", domain: "localhost", path: "/" }]);
  const people = (await (await request.get("/api/customers")).json()).customers;
  const person = people[0];
  const before = (await (await request.get(`/api/customers/${person.id}`)).json()).balancePaise;
  await page.goto("/shop/entry");
  await page.getByRole("combobox", { name: "Customer", exact: true }).selectOption(person.id);
  await page.getByRole("combobox", { name: "Money direction", exact: true }).selectOption("payment_received");
  await page.getByLabel("Amount in rupees", { exact: true }).fill("12.34");
  await page.getByLabel("Note (optional)", { exact: true }).fill("Reviewed exact amount");
  await page.getByRole("button", { name: "Review entry", exact: true }).click();
  await expect(page.getByText("twelve rupees and thirty-four paise", { exact: true })).toBeVisible();
  expect((await (await request.get(`/api/customers/${person.id}`)).json()).balancePaise).toBe(before);
  const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
  expect(audit.violations.filter((v) => v.impact === "serious" || v.impact === "critical").map((v) => v.id)).toEqual([]);
  await page.getByRole("button", { name: "Confirm and record entry", exact: true }).click();
  await expect(page.getByText("Entry recorded.", { exact: true })).toBeVisible();
  expect((await (await request.get(`/api/customers/${person.id}`)).json()).balancePaise).toBe(before - 1234);
  await page.goto("/shop/ledger");
  await page.getByRole("combobox", { name: "Entry type", exact: true }).selectOption("payment_received");
  await page.getByRole("button", { name: "Apply filters", exact: true }).click();
  const row = page.locator("article").filter({ hasText: "₹12.34" });
  await row.getByText("Entry details", { exact: true }).click();
  await expect(row).toContainText("Reviewed exact amount");
  const part = await (await request.get("/api/ledger?limit=2")).json();
  expect(part.rows).toHaveLength(2); expect(part.nextOffset).toBe(2);
  expect((await request.get("/api/ledger?customer=someone-else")).status()).toBe(404);
  await page.screenshot({ path: ".goal/screenshots/entries-390.png", fullPage: true });
});
